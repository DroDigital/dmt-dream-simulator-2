/** Builds data/palettes.json: a 32-colour palette per chart quadrant from the brief's key colours. */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { hexToRgb, oklabToRgb, rgbToHex, rgbToOklab, type RGB } from '../lib/color.ts';

export const QUADRANT_KEYS: Record<string, string[]> = {
  halo: ['#FFF4E6', '#FFC9DE', '#BDE7FF', '#D9C8FF', '#FFE7A3'],
  bloom: ['#FF3D7F', '#FFB000', '#00E0C6', '#7A5CFF', '#FFF27A'],
  hush: ['#0E1A24', '#2E5E6E', '#8FB8B0', '#C9D6D2', '#E8C27A'],
  undertow: ['#0A0614', '#FF2E9A', '#19F0FF', '#6B1FFF', '#B6FF3B'],
};

export function buildPalette(keys: string[]): string[] {
  const out: string[] = [];
  const labs = keys.map((k) => rgbToOklab(hexToRgb(k)));
  // 6 lightness steps per key (30) + warm near-black + pale near-white (never pure black/white)
  for (const [L, a, b] of labs) {
    for (let i = 0; i < 6; i++) {
      const t = i / 5;
      const L2 = 0.18 + t * 0.78;
      const chroma = 1 - Math.abs(t - (L - 0.18) / 0.78) * 0.6;
      out.push(rgbToHex(oklabToRgb([L2, a * chroma, b * chroma]) as RGB));
    }
  }
  out.push('#120E16', '#F6F1EA');
  return out;
}

export function buildAllPalettes(): Record<string, string[]> {
  const res: Record<string, string[]> = {};
  for (const [q, keys] of Object.entries(QUADRANT_KEYS)) res[q] = buildPalette(keys);
  return res;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = resolve(import.meta.dirname, '../../data/palettes.json');
  writeFileSync(out, JSON.stringify({ $comment: 'Generated by tools/import/palettes.ts from the brief quadrant key colours', quadrants: buildAllPalettes(), keys: QUADRANT_KEYS }, null, 1));
  console.log('wrote', out);
}
